import "@testing-library/jest-dom/vitest";

// jsdom does not implement window.matchMedia; components query it for
// prefers-reduced-motion / pointer capabilities during render.
Object.defineProperty(window, "matchMedia", {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
});
